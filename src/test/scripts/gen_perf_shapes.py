#!/usr/bin/env python3
"""Generates src/test/proto/perf_shapes.proto and src/test/java/org/globsframework/grpc/PerfShapes.java.

The four shapes mirror PerfTypeFamily.declare (field counts, kinds, field numbers) so that
ProtobufVsGlobPerfTest compares Globs and protobuf-java on the same messages. Run from the module root:

    python3 src/test/scripts/gen_perf_shapes.py
"""
SHAPES=[6,15,28,45]
KINDS=[("str","string",False),("int","int32",False),("lng","int64",False),("dbl","double",False),("bool","bool",False),
       ("sint","sint32",False),("intArr","int32",True),("lngArr","int64",True),("dblArr","double",True),("strArr","string",True)]
proto=['// Generated by src/test/scripts/gen_perf_shapes.py: the four shapes of PerfTypeFamily, same field numbers,',
 '// for ProtobufVsGlobPerfTest. Regenerate rather than edit.',
 'syntax = "proto3";','','option java_multiple_files = true;','option java_package = "org.globsframework.grpc.perf";',
 'option java_outer_classname = "PerfShapesProto";','','package perf;','']
for s,n in enumerate(SHAPES):
    proto.append(f"message Shape{s} {{")
    for i in range(n-2):
        k=KINDS[i%10]
        proto.append(f"  {'repeated ' if k[2] else ''}{k[1]} {k[0]}{i} = {i+1};")
    proto.append(f"  Shape{s} child = {n-1};")
    proto.append(f"  repeated Shape{s} children = {n};")
    proto.append("}\n")
open("src/test/proto/perf_shapes.proto","w").write("\n".join(proto))

def val(kind, ex):  # ex: java expression for i
    return {"str":f'"value" + {ex}', "int":f"{ex} * 7", "lng":f"{ex} * 1_000_003L", "dbl":f"{ex} + 0.5",
            "bool":f"{ex} % 2 == 0", "sint":f"{ex} * 7"}[kind]
J=["package org.globsframework.grpc;","",
"import org.globsframework.core.metamodel.GlobType;",
"import org.globsframework.core.metamodel.fields.*;",
"import org.globsframework.core.model.Glob;",
"import org.globsframework.core.model.MutableGlob;",
"import org.globsframework.grpc.perf.*;","",
"/**",
" * Builds the values of {@link PerfTypeFamily#fill} — same values, same field numbers — through typed calls on both",
" * sides: the generated protobuf {@code Builder} setters, and {@code MutableGlob.set} on typed {@code Field}s resolved",
" * once. What application code would write, without fill()'s instanceof chain or protobuf's reflective setField.",
" * Generated by src/test/scripts/gen_perf_shapes.py from the shapes of PerfTypeFamily: regenerate rather than edit.",
" */",
"final class PerfShapes {","    private PerfShapes() {","    }",""]
for s,n in enumerate(SHAPES):
    # protobuf
    J.append(f"    static Shape{s} proto{s}(int seed, boolean withChildren) {{")
    J.append(f"        Shape{s}.Builder b = Shape{s}.newBuilder();")
    for i in range(n-2):
        k=KINDS[i%10][0]; cap=k[0].upper()+k[1:]+str(i)
        if k=="intArr": J.append(f"        {{ int i = {i} + seed; b.add{cap}(i).add{cap}(i + 1).add{cap}(i + 2); }}")
        elif k=="lngArr": J.append(f"        {{ int i = {i} + seed; b.add{cap}(i).add{cap}(i + 1).add{cap}(i + 2); }}")
        elif k=="dblArr": J.append(f"        {{ int i = {i} + seed; b.add{cap}(i + 0.5).add{cap}(i + 1.5); }}")
        elif k=="strArr": J.append(f'        {{ int i = {i} + seed; b.add{cap}("a" + i).add{cap}("b" + i); }}')
        else: J.append(f"        b.set{cap}({val(k, f'({i} + seed)')});")
    J.append("        if (withChildren) {")
    J.append(f"            b.setChild(proto{s}(seed + 1, false));")
    J.append(f"            b.addChildren(proto{s}(seed + 2, false)).addChildren(proto{s}(seed + 3, false));")
    J.append("        }")
    J.append("        return b.build();")
    J.append("    }")
    J.append("")
    # glob
    ftype={"str":"StringField","int":"IntegerField","lng":"LongField","dbl":"DoubleField","bool":"BooleanField","sint":"IntegerField",
           "intArr":"IntegerArrayField","lngArr":"LongArrayField","dblArr":"DoubleArrayField","strArr":"StringArrayField"}
    J.append(f"    static final class Glob{s} {{")
    J.append("        private final GlobType type;")
    for i in range(n-2):
        k=KINDS[i%10][0]; J.append(f"        private final {ftype[k]} {k}{i};")
    J.append("        private final GlobField<?> child;")
    J.append("        private final GlobArrayField<?> children;")
    J.append("")
    J.append(f"        Glob{s}(GlobType type) {{")
    J.append("            this.type = type;")
    for i in range(n-2):
        k=KINDS[i%10][0]; J.append(f'            {k}{i} = ({ftype[k]}) type.getField("{k}{i}");')
    J.append('            child = (GlobField<?>) type.getField("child");')
    J.append('            children = (GlobArrayField<?>) type.getField("children");')
    J.append("        }")
    J.append("")
    J.append("        MutableGlob build(int seed, boolean withChildren) {")
    J.append("            MutableGlob g = type.instantiate();")
    for i in range(n-2):
        k=KINDS[i%10][0]
        if k=="intArr": J.append(f"            {{ int i = {i} + seed; g.set({k}{i}, new int[]{{i, i + 1, i + 2}}); }}")
        elif k=="lngArr": J.append(f"            {{ int i = {i} + seed; g.set({k}{i}, new long[]{{i, i + 1, i + 2}}); }}")
        elif k=="dblArr": J.append(f"            {{ int i = {i} + seed; g.set({k}{i}, new double[]{{i + 0.5, i + 1.5}}); }}")
        elif k=="strArr": J.append(f'            {{ int i = {i} + seed; g.set({k}{i}, new String[]{{"a" + i, "b" + i}}); }}')
        else: J.append(f"            g.set({k}{i}, {val(k, f'({i} + seed)')});")
    J.append("            if (withChildren) {")
    J.append("                g.set(child, build(seed + 1, false));")
    J.append("                g.set(children, new Glob[]{build(seed + 2, false), build(seed + 3, false)});")
    J.append("            }")
    J.append("            return g;")
    J.append("        }")
    J.append("    }")
    J.append("")
J.append("}")
open("src/test/java/org/globsframework/grpc/PerfShapes.java","w").write("\n".join(J)+"\n")
